// Writes dist/tokens.css and dist/tokens.json for non-TypeScript consumers (the Go website).
import { mkdirSync, writeFileSync } from "node:fs";
import { colors, categoryColors, radius, space, toCssVars, type } from "../src/index.ts";

const decl = (vars: Record<string, string>) =>
  Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join("\n");
const dark = decl(Object.fromEntries(Object.entries(toCssVars("dark")).filter(([k]) => k.startsWith("--color") || k.startsWith("--category"))));
const css = `/* Generated by packages/tokens/scripts/build-css.ts. Do not edit. */
:root {
${decl(toCssVars("light"))}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${dark}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${dark}
  color-scheme: dark;
}
`;
mkdirSync(new URL("../dist", import.meta.url), { recursive: true });
writeFileSync(new URL("../dist/tokens.css", import.meta.url), css);
writeFileSync(
  new URL("../dist/tokens.json", import.meta.url),
  JSON.stringify({ colors, categoryColors, space, radius, type }, null, 2),
);
console.log("tokens: wrote dist/tokens.css, dist/tokens.json");
